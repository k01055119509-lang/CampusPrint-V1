'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { isolated, configAt, TEST_ROOT, Client, removeTestStorage } = require('../helpers/runtime');
const { createSnapshot, exportAuthority, restoreSnapshot } = require('../../scripts/deploy/backup');
const { startServer } = require('../../backend/server');
const { loadConfig } = require('../../backend/config');
const h = require('../business/helpers');
test('访客版本一致性备份恢复保留单码与旧金额，丢弃会话和恢复授权，重新凭码找单', async t => {
  const original = await isolated(), owner = new Client(original), recovered = new Client(original), admin = new Client(original);
  const targetName = randomUUID(), authorityName = randomUUID(), target = path.join(TEST_ROOT,targetName), authority = path.join(TEST_ROOT,authorityName);
  let restored;
  t.after(async()=>{await restored?.close(); await original.destroy(); await removeTestStorage(targetName); await removeTestStorage(authorityName);});
  await owner.guest(); await recovered.guest(); await admin.admin();
  const order = await h.order(original,owner);
  const reveal = await owner.request('GET',`/api/me/orders/${order.id}/query-code`); assert.equal(reveal.status,200); const code = reveal.body.data.queryCode;
  assert.equal((await recovered.request('POST','/api/orders/recover',{queryCode:code})).status,200);
  const snapshot = await createSnapshot(original); await exportAuthority(original,authority); await original.close();
  const config = { ...loadConfig(), ...configAt(target) };
  const restoration = await restoreSnapshot({snapshotRoot:snapshot.directory,authorityRoot:authority,config}); assert.equal(restoration.orders,1); assert.equal(restoration.restoredFiles,1);
  restored = await startServer(config);
  assert.equal(restored.db.get('SELECT COUNT(*) n FROM sessions').n,0); assert.equal(restored.db.get('SELECT COUNT(*) n FROM order_access_grants').n,0);
  assert.equal(restored.db.get('SELECT totalAmountFen FROM print_orders WHERE id=?',order.id).totalAmountFen,order.totals.totalAmountFen);
  const stale = new Client(restored); stale.cookie = recovered.cookie; assert.equal((await stale.request('GET','/api/auth/me')).status,401);
  const operator = new Client(restored,{surface:'admin'}); await operator.csrfToken();
  assert.equal((await operator.request('POST','/api/auth/admin-login',{username:admin.user.username,password:require('../helpers/runtime').TEST_PASSWORD})).status,200);
  const again = await operator.request('GET',`/api/admin/orders/${order.id}/query-code`); assert.equal(again.status,200); assert.ok(again.body.data.queryCode===code,'restored code is unchanged');
  const visitor = new Client(restored); await visitor.guest();
  const detail = await visitor.request('POST','/api/orders/recover',{queryCode:code}); assert.equal(detail.status,200); assert.equal(detail.body.data.accessType,'recovered');
  assert.equal((await visitor.request('GET',`/api/me/orders/${order.id}/items/${order.items[0].itemId}/file`,undefined,{raw:true})).status,403);
});
